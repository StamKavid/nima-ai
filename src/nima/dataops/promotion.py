"""Explicitly promote verified replay into derived SQL, preserving source freshness."""

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import cast
from uuid import UUID

import psycopg
from psycopg.types.json import Jsonb

from nima.dataops.replay import prepare_replay
from nima.sources.base import SourceAdapter
from nima.storage.connection import connect
from nima.storage.postgres import MigrationError, validate_schema
from nima.storage.runs import run_lock_key


class PromotionError(ValueError):
    """Fixed private-safe promotion reason."""

    def __init__(self, reason: str) -> None:
        self.reason = reason
        super().__init__(reason)


@dataclass(frozen=True)
class Promotion:
    page_count: int
    record_count: int
    normalized_count: int
    quarantined_count: int
    replayed: bool


def _rows(document: dict[str, object]) -> tuple[dict[str, object], list[dict[str, object]]]:
    # Input is generated by prepare_replay, not decoded from a caller-supplied file.
    manifest = {key: value for key, value in document.items() if key != "pages"}
    pages = []
    records = []
    for page in cast(list[dict[str, object]], document["pages"]):
        pages.append({key: value for key, value in page.items() if key != "records"})
        for record in cast(list[dict[str, object]], page["records"]):
            value = cast(dict[str, object] | None, record.get("normalized"))
            records.append(
                {
                    "page_number": page["page_number"],
                    "record_index": record["record_index"],
                    "content_sha256": record["content_sha256"],
                    "status": record["status"],
                    "source_id": value["source_id"] if value is not None else None,
                    "normalized": value,
                    "quarantine_reason": record.get("reason"),
                }
            )
    return {**manifest, "pages": pages}, records


def promote_run(
    dsn: str,
    run_id: UUID,
    archive_root: Path,
    normalizer_version: str,
    replay_sha256: str,
    adapter: SourceAdapter | None = None,
) -> Promotion:
    """Rebuild selected canonical bytes, then atomically persist an explicit SQL batch."""
    if not isinstance(replay_sha256, str) or re.fullmatch("[0-9a-f]{64}", replay_sha256) is None:
        raise PromotionError("promotion_input")
    body, prepared = prepare_replay(dsn, run_id, archive_root, normalizer_version, adapter)
    if prepared.artifact_sha256 != replay_sha256:
        raise PromotionError("promotion_selection")
    document = cast(dict[str, object], json.loads(body))
    source = cast(dict[str, object], document["source_run"])
    if source["status"] not in ("complete", "quarantined"):
        raise PromotionError("promotion_capture")
    manifest, records = _rows(document)
    expected = (
        run_id,
        normalizer_version,
        manifest,
        prepared.page_count,
        prepared.normalized_count,
        prepared.quarantined_count,
    )
    try:
        with connect(dsn) as connection, connection.transaction():
            connection.execute("SET TRANSACTION ISOLATION LEVEL READ COMMITTED")
            validate_schema(connection)
            if connection.execute(
                "SELECT pg_try_advisory_xact_lock_shared(%s)", (run_lock_key(run_id),)
            ).fetchone() != (True,):
                raise PromotionError("promotion_busy")
            current = connection.execute(
                """SELECT jsonb_build_object(
                'run_id',run_id::text,'status',status,'connector_version',connector_version,
                'normalizer_version',normalizer_version,'next_page',next_page,
                'total_records',total_records,'total_pages',total_pages,'page_size',page_size,
                'query',query) FROM nima.ingest_runs WHERE run_id=%s""",
                (run_id,),
            ).fetchone()
            if current is None or current[0] != source:
                raise PromotionError("promotion_scope")
            inserted = connection.execute(
                """INSERT INTO nima_processing.replay_batches
                (replay_sha256,source_run_id,normalizer_version,manifest,page_count,
                 normalized_count,quarantined_count) VALUES (%s,%s,%s,%s,%s,%s,%s)
                ON CONFLICT DO NOTHING RETURNING replay_sha256""",
                (
                    replay_sha256,
                    run_id,
                    normalizer_version,
                    Jsonb(manifest),
                    prepared.page_count,
                    prepared.normalized_count,
                    prepared.quarantined_count,
                ),
            ).fetchone()
            if inserted is not None:
                connection.execute(
                    """INSERT INTO nima_processing.replay_results
                    (replay_sha256,source_run_id,page_number,record_index,content_sha256,
                     status,source_id,normalized,quarantine_reason)
                    SELECT %s,%s,r.* FROM jsonb_to_recordset(%s) AS r(
                        page_number int,record_index int,content_sha256 text,status text,
                        source_id text,normalized jsonb,quarantine_reason text)""",
                    (replay_sha256, run_id, Jsonb(records)),
                )
            else:
                previous = connection.execute(
                    """SELECT source_run_id,normalizer_version,
                    manifest,page_count,normalized_count,quarantined_count
                    FROM nima_processing.replay_batches WHERE replay_sha256=%s""",
                    (replay_sha256,),
                ).fetchone()
                stored = connection.execute(
                    """SELECT jsonb_build_object(
                    'page_number',page_number,'record_index',record_index,
                    'content_sha256',content_sha256,'status',status,'source_id',source_id,
                    'normalized',normalized,'quarantine_reason',quarantine_reason)
                    FROM nima_processing.replay_results WHERE replay_sha256=%s
                    ORDER BY page_number,record_index""",
                    (replay_sha256,),
                ).fetchall()
                if previous != expected or [row[0] for row in stored] != records:
                    raise PromotionError("promotion_conflict")
    except MigrationError:
        raise PromotionError("promotion_schema") from None
    except psycopg.Error:
        raise PromotionError("promotion_database") from None
    return Promotion(
        prepared.page_count,
        prepared.record_count,
        prepared.normalized_count,
        prepared.quarantined_count,
        inserted is None,
    )
